const fs = require('node:fs');
const vm = require('node:vm');
const assert = require('node:assert/strict');
const source = fs.readFileSync(__dirname + '/wrc-bulk-uploader.user.js', 'utf8');
const context = vm.createContext({ Map, Set, Array, URL });
vm.runInContext(source.slice(source.indexOf('  function startDownloadView'), source.indexOf('  const SCRIPT_VERSION')), context);
const mapping = context.parseDownloadMetadata('Select,Folder Path\n1,Top > A > Child > Deep:Top > B > Child\n2,Top > A\n3,Top > A > Child\n4,Elsewhere > A > Child\n5,Top > AA > Child');
const displayed = ['1','2','3','4','5'].map(id => ({id,name:id+'.pdf'}));
const selection = {rules:new Map([['Top > A',true]])};
const snapshot={schema:1,csv:'Select,Folder Path\n1,Top > A',name:'mapping.csv',importedAt:'2026-10-12T00:00:00Z',rules:[]};
assert.equal(context.restoreDownloadMapping(snapshot).selection.rules.size,0,'Empty stored selection is valid and must stay empty');
assert.throws(()=>context.restoreDownloadMapping({...snapshot,schema:2}),/Unsupported/);
assert.throws(()=>context.restoreDownloadMapping({...snapshot,importedAt:'bad'}),/Unsupported/);
assert.throws(()=>context.restoreDownloadMapping({...snapshot,rules:[['Top',true],['Top',false]]}),/Invalid saved/);
assert.throws(()=>context.restoreDownloadMapping({...snapshot,rules:[['Top','true']]}),/Invalid saved/);
const plan = () => JSON.parse(JSON.stringify(context.planMappedDownloads(displayed,mapping,selection)));
assert.equal(plan().copies,3);
assert.deepEqual(plan().files.find(x=>x.id==='1').paths,[['A','Child','Deep']]);
context.setDownloadFolderSelection(selection,'Top > A > Child',false);
assert.deepEqual(plan().files.map(x=>x.id),['2'],'Parent document retained; excluded branch and descendants absent');
context.setDownloadFolderSelection(selection,'Top > A > Child > Deep',true);
assert.deepEqual(plan().files.map(x=>x.id),['1','2'],'Reinclude a descendant under excluded branch');
assert.equal(context.downloadFolderStates(mapping.folders,selection).get('Top > A > Child').mixed,true);
context.setDownloadFolderSelection(selection,'Top > B',true);
assert.deepEqual(plan().files.find(x=>x.id==='1').paths,[['A','Child','Deep'],['B','Child']],'One file copied to both selected branches without ancestor duplication');
assert.equal(plan().files.some(x=>x.id==='5'),false,'A selection must not include similarly prefixed AA');
context.setDownloadFolderSelection(selection,'Elsewhere > A',true);
assert.deepEqual(plan().files.find(x=>x.id==='4').paths,[['Elsewhere','A','Child']],'Different top-level trees retain ancestry to avoid collisions');
context.setDownloadFolderSelection(selection,'Top > A',true);
assert.equal(selection.rules.has('Top > A > Child'),false,'Reticking parent clears descendant exclusions');
selection.rules.clear();
for(const root of mapping.folders.filter(path=>!path.includes(' > '))) selection.rules.set(root,true);
assert.equal(plan().copies,6,'Select all includes every mapped assignment');
context.setDownloadFolderSelection(selection,'Top',false);
assert.deepEqual(plan().files.map(x=>x.id),['4'],'Untick selected top-level branch excludes all its documents');
selection.rules.clear();
assert.throws(plan,/Choose a mapped folder/);
selection.rules.set('Unknown',true);
assert.throws(plan,/Choose a mapped folder/);
console.log('Folder picker planning checks passed: nested exclusions, re-inclusions, multiple roots, shared files, all/none, path isolation.');
